#!/usr/bin/env python3
"""Generates views/calculator.dmvs: the keys are a grid of boxes whose size follows the size the application is given ($view.w, $view.h).

A key is a box with a handler that tells the application which key it is (EMIT "press", <ascii>); a pressed key is drawn inverted.
Run it from the root of the repository after changing the layout: python3 scripts/gen_view.py > views/calculator.dmvs
"""
ROWS = [
    [("C", "c", "fn"), ("+-", "n", "fn"), ("%", "%", "fn"), ("/", "/", "op")],
    [("7", "7", ""), ("8", "8", ""), ("9", "9", ""), ("x", "*", "op")],
    [("4", "4", ""), ("5", "5", ""), ("6", "6", ""), ("-", "-", "op")],
    [("1", "1", ""), ("2", "2", ""), ("3", "3", ""), ("+", "+", "op")],
    [("0", "0", ""), (".", ".", ""), ("<", "b", "fn"), ("=", "=", "op")],
]

out = []
w = out.append
w("""; calculator: a pocket calculator for the part of the screen it is given. Generated by scripts/gen_view.py - change that, not this.
;
; The display (two lines: the operation waiting and the number) is on top, under it a grid of 4 x 5 keys. Everything follows $view.w and
; $view.h, so it fits any rent. The application sets the properties $expr and $text and is told of a key by the event "press" (the value
; is the ASCII code of the key: 0-9 . + - * / = % and n (sign), b (erase), c (clear)).
.view   calculator
.entry  draw

.font   big,   "builtin-16"
.font   small, "builtin-8"

.prop   $expr, str[48], "",  "expr"
.prop   $text, str[24], "0", "text"

.var    $m,   int, 0         ; the margin
.var    $dh,  int, 0         ; the height of the display
.var    $kw,  int, 0         ; the size of a key (the grid, less the gaps)
.var    $kh,  int, 0
.var    $x0,  int, 0         ; the left sides of the columns
.var    $x1,  int, 0
.var    $x2,  int, 0
.var    $x3,  int, 0
.var    $y0,  int, 0         ; the tops of the rows
.var    $y1,  int, 0
.var    $y2,  int, 0
.var    $y3,  int, 0
.var    $y4,  int, 0
.var    $tw,  int, 0         ; the width of the display's texts
.var    $fw,  int, 0         ; the width of its frame

draw:
        BOX     @all, 0, 0, $view.w, $view.h, OPAQUE
        FILL    #FFFFFF

        ; the layout: 5 px around and between the keys, the display takes the top part (a fifth of the height, at least 56)
        SET     $m, 5
        SET     $dh, $view.h
        DIV     $dh, 5
        JGE     $dh, 56, .tall
        SET     $dh, 56
.tall:
        SET     $kw, $view.w
        SUB     $kw, 25
        DIV     $kw, 4
        SET     $kh, $view.h
        SUB     $kh, $dh
        SUB     $kh, 30
        DIV     $kh, 5
        SET     $x0, 5
        SET     $x1, $x0
        ADD     $x1, $kw
        ADD     $x1, 5
        SET     $x2, $x1
        ADD     $x2, $kw
        ADD     $x2, 5
        SET     $x3, $x2
        ADD     $x3, $kw
        ADD     $x3, 5
        SET     $y0, $dh
        ADD     $y0, 5
        SET     $y1, $y0
        ADD     $y1, $kh
        ADD     $y1, 5
        SET     $y2, $y1
        ADD     $y2, $kh
        ADD     $y2, 5
        SET     $y3, $y2
        ADD     $y3, $kh
        ADD     $y3, 5
        SET     $y4, $y3
        ADD     $y4, $kh
        ADD     $y4, 5
        SET     $tw, $view.w
        SUB     $tw, 16
        SET     $fw, $view.w
        SUB     $fw, 6

        ; the display
        FRAME   3, 3, $fw, $dh, 2, #000000
        TEXT    8, 12, $tw, 10, $expr, small, #000000, RIGHT
        TEXT    8, 28, $tw, 18, $text, big, #000000, RIGHT
""")
for r, row in enumerate(ROWS):
    for c, (label, code, kind) in enumerate(row):
        ident = "k%d%d" % (r, c)
        w("        BOX     @%s, $x%d, $y%d, $kw, $kh, OPAQUE" % (ident, c, r))
        w("        ON      CLICK, h_%s" % ident)
        w("        JNE     $box.pressed, 0, .%s_down" % ident)
        if kind == "op":
            w("        FILL    #000000")
            w("        TEXT    0, 0, $box.w, $box.h, \"%s\", big, #FFFFFF, CENTER|MIDDLE" % label)
        else:
            w("        FILL    #FFFFFF")
            w("        RFRAME  0, 0, $box.w, $box.h, 6, %d, #000000" % (3 if kind == "fn" else 2))
            w("        TEXT    0, 0, $box.w, $box.h, \"%s\", big, #000000, CENTER|MIDDLE" % label)
        w("        JMP     .%s_done" % ident)
        w(".%s_down:" % ident)
        if kind == "op":
            w("        FILL    #FFFFFF")
            w("        RFRAME  0, 0, $box.w, $box.h, 6, 3, #000000")
            w("        TEXT    0, 0, $box.w, $box.h, \"%s\", big, #000000, CENTER|MIDDLE" % label)
        else:
            w("        FILL    #000000")
            w("        TEXT    0, 0, $box.w, $box.h, \"%s\", big, #FFFFFF, CENTER|MIDDLE" % label)
        w(".%s_done:" % ident)
        w("        END")
w("        END")
w("        RET")
w("")
for r, row in enumerate(ROWS):
    for c, (label, code, kind) in enumerate(row):
        w("h_k%d%d:" % (r, c))
        w("        EMIT    \"press\", %d" % ord(code))
        w("        RET")
print("\n".join(out))
